//! The docs' component gallery (`/components/`) is built by the static
//! engine, which has no database and no `request` routes, so the
//! feature-gated groups (Listings, Forms, Accounts, App UI, and Commerce
//! later) cannot render there. This test renders them with the engine's
//! real templates and extensions (sample data stands in for the database)
//! and keeps `docs/templates/gallery/<group>.html` in step: it fails when a
//! file is out of date. To regenerate after changing a component:
//!
//! ```sh
//! WROUGHT_UPDATE_GALLERY=1 cargo test -p engine-cli --all-features --test gallery
//! ```
//!
//! Needs every feature (`--all-features`); no database.

#![cfg(all(
    feature = "content",
    feature = "search",
    feature = "forms",
    feature = "auth",
    feature = "media",
    feature = "roles",
    feature = "payments"
))]

use std::path::{Path, PathBuf};
use std::sync::Arc;

use engine_core::builder::SiteExtension;
use engine_core::components::{Catalogue, GROUPS};
use minijinja::context;
use minijinja::value::{Kwargs, Value};

fn docs() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs")
}

fn dirs() -> Vec<&'static include_dir::Dir<'static>> {
    let mut v: Vec<&'static include_dir::Dir<'static>> = vec![
        &engine_content::render::LISTINGS,
        &engine_search::ext::COMPONENTS,
        &engine_auth::site::COMPONENTS,
        &engine_payments::site::COMPONENTS,
    ];
    v.extend(engine_forms::component_dirs());
    v.extend(engine_core::templates::core_dirs());
    v
}

fn sample_items() -> Value {
    Value::from_serialize(serde_json::json!([
        {"title": "Wrought iron, explained", "url": "/articles/wrought-iron/", "published_at": "2026-11-20T09:00:00Z",
         "summary": "Why iron worked by hand lasts for centuries."},
        {"title": "A forge in every town", "url": "/articles/forge/", "published_at": "2026-11-12T09:00:00Z",
         "summary": "How smiths kept a region's tools working."},
    ]))
}

/// Stand-ins for the database-backed functions of `content` and `search`.
fn add_sample_functions(env: &mut minijinja::Environment<'static>) {
    env.add_function("list_items", |_t: String, _k: Kwargs| sample_items());
    env.add_function("related_items", |_t: String, _id: Value, _k: Kwargs| {
        sample_items()
    });
    env.add_function("term_counts", |_v: String| {
        Value::from_serialize(serde_json::json!([
            {"name": "Craft", "slug": "craft", "url": "/topics/craft/", "count": 4, "weight": 5},
            {"name": "History", "slug": "history", "url": "/topics/history/", "count": 2, "weight": 3},
            {"name": "Tools", "slug": "tools", "url": "/topics/tools/", "count": 1, "weight": 1},
        ]))
    });
    env.add_function("search_path", || "/search/".to_string());
    env.add_function("search", |q: Value, _k: Kwargs| {
        let hits: Vec<Value> = vec![
            context! {
                title => "Wrought iron, explained",
                url => "/articles/wrought-iron/",
                snippet => Value::from_safe_string("Why <mark>iron</mark> worked by hand lasts.".into()),
                published_at => "2026-11-20T09:00:00Z",
            },
        ];
        context! { query => q, total => 1, page => 1, pages => 1, hits => hits }
    });
}

fn render_group(env: &minijinja::Environment<'static>, cat: &Catalogue, group: &str) -> String {
    let mut out = String::from(
        "{#- Generated by crates/engine-cli/tests/gallery.rs from the engine's own\n    \
         templates with sample data; do not edit. Regenerate with\n    \
         WROUGHT_UPDATE_GALLERY=1 cargo test -p engine-cli --all-features --test gallery -#}\n{% raw %}\n",
    );
    let comps: Vec<_> = cat
        .components()
        .iter()
        .filter(|c| c.group == group && c.features != ["core"])
        .collect();
    if comps.is_empty() {
        out.push_str("<p>No components in this group yet.</p>\n");
    }
    for c in comps {
        // Accounts components that only show for a signed-in visitor.
        // Accounts and Commerce components that show their forms to a
        // signed-in visitor.
        let signed_in =
            ["profile_form", "account_menu"].contains(&c.name.as_str()) || c.group == "commerce";
        let user = if signed_in {
            context! { id => 1, name => "Ada Lovelace", email => "ada@example.org", admin => false }
        } else {
            Value::from(())
        };
        let html = env
            .render_str(
                r#"{% from "partials/component_entry.html" import entry %}{{ entry(c, component(c.name, c.example), note) }}"#,
                context! {
                    c => {
                        let mut m = engine_core::templates::value_map(&Value::from_serialize(c));
                        m.insert("example".into(), c.example_value());
                        Value::from(m)
                    },
                    note => signed_in.then_some("Shown as for a signed-in visitor."),
                    site => context! { name => "Wrought", language => "en" },
                    page => context! { url => "/components/", title => "Component gallery" },
                    request => context! { path => "/components/", args => context! {} },
                    csrf => "example-csrf-token",
                    user => user,
                },
            )
            .unwrap_or_else(|e| panic!("{}: {e:#}", c.name));
        out.push_str(&scrub(&html));
    }
    out.push_str("{% endraw %}\n");
    out
}

/// Replace per-render values (the forms' time-trap stamp) with fixed ones.
fn scrub(html: &str) -> String {
    let mut out = String::new();
    let mut rest = html;
    let key = "name=\"_t\" value=\"";
    while let Some(i) = rest.find(key) {
        out.push_str(&rest[..i + key.len()]);
        rest = &rest[i + key.len()..];
        let end = rest.find('"').unwrap_or(0);
        out.push_str("example-stamp");
        rest = &rest[end..];
    }
    out.push_str(rest);
    out
}

#[test]
fn gallery_snapshots_of_feature_gated_groups_are_current() {
    let docs = docs();
    let templates = docs.join("templates");
    let cat = Arc::new(Catalogue::load(&dirs(), Some(&templates)).unwrap());
    let mut env = engine_core::templates::environment(
        Some(templates.clone()),
        Arc::default(),
        "https://wrought.kovirlabs.org".into(),
        dirs(),
        cat.clone(),
    );
    engine_core::appui::register(&mut env);
    let mut auth_cfg = toml::Table::new();
    auth_cfg.insert("registration".into(), "open".into());
    let ac = engine_auth::AuthConfig::from_site(Some(&auth_cfg)).unwrap();
    engine_auth::site::AccountsExtension::new(&ac).extend_env(&mut env);
    let rt = tokio::runtime::Runtime::new().unwrap();
    let forms = rt
        .block_on(engine_forms::Forms::open(&docs, None, rt.handle().clone()))
        .unwrap();
    forms.extension().extend_env(&mut env);
    add_sample_functions(&mut env);
    env.add_global(
        "shop",
        context! {
            cart_page => "/shop/cart/", cart_action => "/_engine/shop/cart/",
            checkout_action => "/_engine/shop/checkout/",
        },
    );

    let update = std::env::var_os("WROUGHT_UPDATE_GALLERY").is_some();
    let mut stale = Vec::new();
    for (group, _) in GROUPS {
        if ["layout", "navigation", "content"].contains(group) {
            continue;
        }
        let html = render_group(&env, &cat, group);
        assert!(!html.contains("<script>alert"));
        let path = templates.join(format!("gallery/{group}.html"));
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != html {
            if update {
                std::fs::create_dir_all(path.parent().unwrap()).unwrap();
                std::fs::write(&path, &html).unwrap();
            } else {
                stale.push(path.display().to_string());
            }
        }
    }
    assert!(
        stale.is_empty(),
        "out of date: {stale:?}; run WROUGHT_UPDATE_GALLERY=1 cargo test -p engine-cli \
         --all-features --test gallery"
    );
}
